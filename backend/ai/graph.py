def extract_resume_data(state:AgentState):
    print('extract_resume_data')
    """Extract the data from the resume
    Args:
    state(dict):The current graph state
    Returns:
    State(dict): New key added to state
    """
    file_path=state['file_path']
    loader=PyPDFLoader(file_path=file_path)
    text_splitter=RecursiveCharacterTextSplitter(chunk_size=1000,chunk_overlap=200)
    docs=loader.load_and_split(text_splitter=text_splitter)
    
    user_id=state['user_id']
    for doc in docs:
        doc.metadata["user_id"] = user_id

    user_id=state['user_id']
    print('user_id',user_id)
    astra_vector_store.add_documents(docs)


    llm=ChatAnthropic(model="claude-sonnet-4-6", anthropic_api_key=anthropic_api_key)
    llm=llm.bind_tools(tools)

    retriever = astra_vector_store.as_retriever(
        search_type="similarity",
        search_kwargs={
            "filter": {"user_id": user_id}  # only this user's docs
        }
    )

    return {
        "messages":llm.invoke(state['messages']),
        "documents": [doc.page_content for doc in docs],
        "retriever": retriever
    }
    

def chat(state:AgentState):
    print('chat node')
    """
    Get answers to the question regarding the applicant
    Args:
    state(dict): The current graph state

    Returns:
    State(dict): New key added to state
    """
    question = ""
    last_msg = state['messages'][-1]

    # If last message is from AI (response to tool), get the user question before it
    if isinstance(last_msg, AIMessage):
        raw = state['messages'][-2].content
    else:
        raw = last_msg.content

    if isinstance(raw, list):
        question = " ".join(
            block.get("text", "") for block in raw if isinstance(block, dict)
        )
    else:
        question = raw
    
    
    

    SYSTEM_PROMPT = """You are an advanced resume analysis assistant.

Your task is to answer questions about a candidate by returning ONLY a valid JSON object.

Return this exact JSON structure (no other text):
{{
  "generation": "your detailed answer here",
  "applicant": {{
    "name": "full name or null",
    "skills": ["skill1", "skill2"] or [],
    "education": "education or null",
    "work_experience": ["experience1", "experience2"] or [],
    "certifications": ["cert1"] or [],
    "achievements": ["achievement1"] or []
  }},
  "confidence": 0.0-1.0,
  "source": "resume" or "inference",
  "missing_data": []
}}

Instructions:
- Answer ONLY using information from the resume context.
- If information is not in resume, use "inference" as source and infer logically.
- Do NOT invent facts - if unknown, use null or empty arrays.
- generation should be a concise paragraph summarizing the analysis.

Resume Context:
{context}

==============================
Chat History:
{chat_history}
=============================="""

    prompt=ChatPromptTemplate.from_messages([("system",SYSTEM_PROMPT),("human","{input}")])

    user_id=state['user_id']
    print('user-id',user_id)

    retriever = astra_vector_store.as_retriever(
        search_type="similarity",
        search_kwargs={
            "filter": {"user_id": user_id}  # only this user's docs
        }
    )

    docs = retriever.invoke(question)
    context_str = "\n".join(doc.page_content for doc in docs) if docs else ""
    print(f'docs count: {len(docs) if docs else 0}')
    print(f'context_str length: {len(context_str)}')
    print(f'question: {question[:100] if question else "EMPTY"}')

    # Use ChatAnthropic with structured output for JSON responses
    chat_llm = ChatAnthropic(model="claude-sonnet-4-6", anthropic_api_key=anthropic_api_key)
    chat_llm_with_response = chat_llm.with_structured_output(LLMResponseStructure)

    rag_chain = (
        {
            "context": RunnableLambda(lambda x: context_str),
            "input": RunnableLambda(lambda x: question),
            "chat_history": RunnableLambda(lambda x: chat_history)
        }
        | prompt
        | chat_llm_with_response
    )

    res=rag_chain.invoke({"input": question, "chat_history": chat_history})
    print('rag_chain result type:', type(res))
    

    return {
        "answer":res,
    }


def build_graph():
    workflow=StateGraph(AgentState)
    tool_node=ToolNode(tools=tools)
    workflow.add_node('extract_resume_data',extract_resume_data)
    workflow.add_node('chat',chat)
    workflow.add_node('tools',tool_node)
    workflow.add_node('checkResponse',checkResponse)

    workflow.add_conditional_edges(
        START,
        route_question,
        {
            'extract_resume_data':'extract_resume_data',
            'chat':'chat'
        }
    )

    workflow.add_conditional_edges(
        'extract_resume_data',
        tools_condition
    )
    workflow.add_edge('tools', 'extract_resume_data')
    workflow.add_edge('extract_resume_data', 'chat')
    workflow.add_conditional_edges(
        'chat',
        checkResponse,
        {
            'chat':'chat',
            'end':END
        }
    )

    graph=workflow.compile(checkpointer=memory)

    return graph

graph=build_graph()


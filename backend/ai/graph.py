class Answer(BaseModel):
    name: Optional[str] = Field(None, description="Full name of the applicant")
    skills: Optional[List[str]] = Field(default_factory=list, description="Technical and soft skills of the applicant")
    education: Optional[str] = Field(None, description="Education background of the applicant")
    work_experience: Optional[List[str]] = Field(default_factory=list, description="Work experience of the applicant")
    certifications: Optional[List[str]] = Field(default_factory=list, description="List of certifications the applicant has")
    achievements: Optional[List[str]] = Field(default_factory=list, description="List of achievements of the applicant")

Answer.model_rebuild()

class LLMResponseStructure(BaseModel):
    generation: Optional[str] = Field(None, description="Answer generated by the llm")
    applicant: Optional[Answer] = Field(None, description="The data of the applicant")
    confidence: Optional[float] = Field(None, description="0.0 = low confidence, 1.0 = high confidence")
    source: Optional[Literal['resume', 'inference']] = Field(None, description="source of the answer")
    missing_data: Optional[List[str]] = Field(default_factory=list, description="MUST be a JSON array. Use [] if nothing is missing. Never use a plain string.")

    @field_validator('missing_data', mode='before')
    @classmethod
    def coerce_missing_data(cls, v):
        if v is None or v == "":
            return []
        if isinstance(v, str):
            return [v]
        return v

LLMResponseStructure.model_rebuild()


